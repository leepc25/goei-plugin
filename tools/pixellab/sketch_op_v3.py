"""손길 의원 수술실 3차 배치 밑그림 (632×424, 참고 그림용). 사용: python3 sketch_jinryo_v2.py <출력폴더>"""
import sys
from PIL import Image, ImageDraw
P = sys.argv[1]
W, H = 632, 424; VX, VY = 316, 52          # 소실점
im = Image.new('RGB', (W, H), (200, 200, 200)); d = ImageDraw.Draw(im); O = (40, 40, 40)
def poly(pts, fill): d.polygon([tuple(map(round, p)) for p in pts], fill=fill, outline=O)
def rect(x0, y0, x1, y1, fill): d.rectangle([x0, y0, x1, y1], fill=fill, outline=O)
def back(x, y, yb):   # 바닥 점 (x, y)를 더 안쪽 바닥 yb로 (소실점으로)
    s = (yb - VY) / (y - VY); return VX + (x - VX) * s, s
def box(x0, x1, yf, h, dep, front, top, side):
    yb = yf - dep; bx0, s = back(x0, yf, yb); bx1, _ = back(x1, yf, yb); hb = h * s
    poly([(x0, yf - h), (x1, yf - h), (bx1, yb - hb), (bx0, yb - hb)], top)
    if x1 < VX: poly([(x1, yf - h), (bx1, yb - hb), (bx1, yb), (x1, yf)], side)
    elif x0 > VX: poly([(x0, yf - h), (bx0, yb - hb), (bx0, yb), (x0, yf)], side)
    rect(x0, yf - h, x1, yf, front)
# 크기 기준 사람 (그리지 말 것)
def person(x, y, h):
    w = h * 0.26; c = (128, 128, 128); d.ellipse([x - w * 0.35, y - h, x + w * 0.35, y - h + h * 0.14], fill=c); d.rectangle([x - w / 2, y - h + h * 0.14, x + w / 2, y], fill=c)
TILE = (232, 236, 236); GR = (200, 205, 206)
def floorpt(x, y): return (x, y)
# 뒷벽 (흰 타일), 천장 띠
rect(0, 0, W, 14, (150, 150, 150))
poly([(95, 14), (537, 14), (537, 255), (95, 255)], TILE)
for y in range(32, 255, 18): d.line([(95, y), (537, y)], fill=GR)
for x in range(95, 537, 18): d.line([(x, 14), (x, 255)], fill=GR)
# 바닥: 회청색 타일, 줄눈이 소실점으로 모임 + 가로줄(깊이)
poly([(0, 342), (95, 255), (537, 255), (632, 342), (632, H), (0, H)], (140, 160, 172))
for x in range(-600, 1300, 40):   # 앞쪽 바닥 끝 x에서 소실점 쪽으로
    t = (255 - H) / (VY - H); d.line([(x, H), (x + (VX - x) * t, 255)], fill=(120, 140, 152))
for y in (262, 272, 285, 302, 324, 352, 388):
    xl = 95 - (y - 255) * 95 / 87 if y < 342 else 0; xr = 537 + (y - 255) * 95 / 87 if y < 342 else W
    d.line([(max(0, xl), y), (min(W, xr), y)], fill=(120, 140, 152))
d.ellipse([300, 395, 332, 405], fill=(80, 90, 100), outline=O)                      # 배수구
d.ellipse([230, 345, 400, 375], fill=(170, 190, 200))                              # 조명 반사
# 옆벽 (타일, 소실점으로)
for side in (-1, 1):
    xw = 95 if side < 0 else 537; xe = 0 if side < 0 else W
    poly([(xe, -2), (xw, 14), (xw, 255), (xe, 342)], (222, 226, 226))
    for k in range(1, 6):
        x = xw + (xe - xw) * k / 6; s = (x - VX) / (xw - VX)
        d.line([(x, VY + (14 - VY) * s), (x, VY + (255 - VY) * s)], fill=GR)
    for y0 in range(32, 255, 18):
        d.line([(xw, y0), (xe, VY + (y0 - VY) * (xe - VX) / (xw - VX))], fill=GR)
rect(150, 4, 280, 10, (250, 250, 250)); rect(352, 4, 482, 10, (250, 250, 250))
# 오른쪽 벽: 이상한 의수족·이식 장비가 걸린 철제 벽 선반 (벽 면을 따라 비스듬히)
def rw(x, y):   # 오른쪽 벽 위 점: x(537~632), 높이 y(뒷벽 기준)
    s_ = (x - VX) / (537 - VX); return (x, VY + (y - VY) * s_)
for yb in (110, 160, 210):
    poly([rw(550, yb), rw(620, yb), rw(620, yb + 5), rw(550, yb + 5)], (120, 120, 125))
for i, (x, yb, c) in enumerate(((556, 110, (150, 120, 90)), (575, 110, (90, 95, 100)), (596, 110, (170, 140, 100)), (560, 160, (90, 95, 100)), (585, 160, (180, 150, 110)), (606, 160, (100, 110, 120)), (570, 210, (130, 135, 140)), (600, 210, (60, 160, 200)))):
    a1, b1 = rw(x, yb - 30), rw(x + 10, yb)
    d.rectangle([a1[0], a1[1], b1[0], b1[1]], fill=c, outline=O)
# 뒷벽: 사슬 약품장, 세면대, 냉장고, 폐기물 통, 장갑 상자 선반, 주사기 수거함
rect(110, 90, 190, 255, (150, 155, 160)); rect(116, 97, 148, 195, (180, 205, 215)); rect(152, 97, 184, 195, (180, 205, 215))
for y in (125, 155): d.line([(116, y), (184, y)], fill=O)
for i, x in enumerate(range(119, 183, 6)):
    for y in (112, 140, 170): d.rectangle([x, y, x + 3, y + 10], fill=[(130, 70, 30), (210, 210, 220)][(i + y) % 2])
d.line([(116, 140), (184, 160)], fill=(90, 90, 90), width=3); d.line([(116, 160), (184, 140)], fill=(90, 90, 90), width=3); rect(145, 146, 155, 157, (200, 170, 60))
rect(205, 182, 268, 197, (200, 205, 210)); rect(212, 197, 261, 255, (215, 218, 222)); rect(234, 158, 239, 182, (170, 170, 175))
rect(205, 120, 268, 150, (205, 205, 210)); [rect(208 + i * 15, 125, 220 + i * 15, 145, c) for i, c in enumerate([(120, 170, 220), (240, 240, 240), (120, 200, 150), (240, 240, 240)])]
box(425, 500, 262, 172, 26, (250, 250, 252), (235, 235, 238), (215, 215, 220))
rect(486, 115, 493, 205, (110, 110, 115)); d.line([(425, 125), (500, 125)], fill=(150, 150, 155), width=2)
for y in range(238, 258, 4): d.line([(435, y), (490, y)], fill=(170, 170, 175))
rect(400, 150, 415, 175, (230, 200, 60))
box(508, 530, 262, 30, 6, (200, 40, 40), (220, 70, 70), (170, 30, 30))
box(410, 445, 300, 20, 14, (235, 240, 245), (215, 225, 235), (200, 210, 220)); box(412, 443, 280, 16, 12, (90, 140, 210), (120, 165, 225), (70, 115, 180))
# 무영등: 두 개 머리
d.line([(316, 14), (316, 80)], fill=(150, 150, 155), width=5)
for cx in (285, 345):
    d.line([(316, 80), (cx, 100)], fill=(150, 150, 155), width=4); d.ellipse([cx - 30, 95, cx + 30, 122], fill=(235, 238, 240), outline=O); d.ellipse([cx - 16, 101, cx + 16, 116], fill=(255, 255, 230), outline=O)
person(395, 262, 142)
# 링거대·생체 모니터(바퀴 스탠드)
d.line([(205, 210), (205, 350)], fill=(150, 150, 155), width=3); rect(198, 210, 212, 232, (200, 230, 240)); d.line([(193, 350), (217, 350)], fill=(120, 120, 125), width=3)
d.line([(455, 230), (455, 350)], fill=(150, 150, 155), width=3); rect(438, 205, 472, 232, (40, 45, 50)); d.line([(442, 220), (468, 214)], fill=(80, 220, 120), width=2); d.line([(443, 350), (467, 350)], fill=(120, 120, 125), width=3)
# 수술대: 크고 높게 (사람 키의 약 0.53), 가운데
rect(296, 300, 336, 368, (150, 155, 160)); box(255, 377, 373, 7, 16, (120, 125, 130), (140, 145, 150), (110, 115, 120))
box(222, 410, 302, 14, 26, (170, 175, 180), (40, 40, 45), (130, 135, 140))
rect(245, 270, 300, 279, (245, 245, 245)); d.line([(236, 290), (236, 304)], fill=(110, 70, 40), width=3); d.line([(396, 290), (396, 304)], fill=(110, 70, 40), width=3)
# 기구 수레 둘 (양옆, 다리)
for x0 in (130, 488):
    box(x0, x0 + 48, 288, 5, 14, (190, 195, 200), (225, 228, 232), (160, 165, 170))
    for x in (x0 + 3, x0 + 45): d.line([(x, 288), (x, 352)], fill=(140, 140, 145), width=3)
    box(x0, x0 + 48, 334, 4, 14, (190, 195, 200), (210, 212, 215), (160, 165, 170))
    for x in (x0 + 10, x0 + 20, x0 + 30): d.line([(x, 274), (x + 6, 280)], fill=(90, 90, 95), width=2)
# 산소통 수레 (왼쪽 앞), 흡인기 수레(오른쪽 앞)
box(40, 70, 395, 8, 10, (90, 90, 95), (110, 110, 115), (70, 70, 75)); rect(48, 300, 62, 388, (60, 140, 80)); rect(51, 290, 59, 300, (180, 180, 185))
box(560, 600, 400, 60, 14, (200, 205, 210), (225, 228, 232), (170, 175, 180)); rect(568, 325, 590, 340, (220, 240, 250))
box(78, 118, 410, 62, 16, (150, 155, 160), (175, 180, 185), (130, 135, 140))
for k, yy in enumerate(range(352, 410, 8)): d.rectangle([78, yy, 118, yy + 4], fill=(230, 200, 40) if k % 2 == 0 else (30, 30, 30))
person(170, 418, 168)
im.save(P + '/op3_sketch.png'); im.resize((W * 2, H * 2), Image.NEAREST).save(P + '/op3_sketch_x2.png')
