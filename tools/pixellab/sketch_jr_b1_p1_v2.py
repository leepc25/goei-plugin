"""중림 앞골목 ① v2 밑그림: 뒷벽 아래 선 y254(60%) 수평, 바닥 아래 40%(선 없음), 왼쪽 계단(옆모습), 오른쪽 끝 기둥, 가운데 벽 안으로 들어간 가게 + 통로로 나온 카운터, 사람 크기(뒤 142·앞 167, 그리지 말 것)."""
import sys
from PIL import Image, ImageDraw
P = sys.argv[1]
W, H, Y = 632, 424, 254
im = Image.new('RGB', (W, H)); d = ImageDraw.Draw(im); O = (30, 30, 30)
def poly(pts, fill): d.polygon(pts, fill=fill, outline=O)
poly([(0, 0), (W, 0), (W, 22), (0, 22)], (70, 70, 75))            # 천장 띠
poly([(0, 22), (W, 22), (W, Y), (0, Y)], (135, 130, 120))          # 뒷벽
poly([(0, Y), (W, Y), (W, H), (0, H)], (105, 105, 105))            # 바닥: 한 면, 선 없음
for x in (150, 360): d.rectangle([x, 8, x + 110, 13], fill=(240, 240, 230))   # 형광등
# 왼쪽 옆벽(왼쪽 끝에서만 비스듬히)과 계단: 앞 바닥에서 뒤·위로 올라가 왼쪽 위로 사라짐
poly([(0, 0), (40, 22), (40, Y), (0, H)], (115, 110, 100))
for i in range(14):
    y0 = 410 - i * 26; x0 = 120 - i * 6
    poly([(x0 - 120, y0 - 26), (x0, y0 - 26), (x0, y0), (x0 - 120, y0)], (95 + (i % 2) * 20, 95 + (i % 2) * 20, 95 + (i % 2) * 20))
d.line([(130, 410), (40, 40)], fill=(60, 60, 60), width=3)       # 난간
# 가게: 벽 안으로 들어간 방(안쪽 옆벽·천장 보임)
poly([(150, 70), (540, 70), (540, Y), (150, Y)], (60, 40, 30))
poly([(150, 70), (190, 95), (190, 235), (150, Y)], (150, 95, 60))
poly([(540, 70), (500, 95), (500, 235), (540, Y)], (150, 95, 60))
poly([(150, 70), (540, 70), (500, 95), (190, 95)], (170, 120, 80))
poly([(190, 95), (500, 95), (500, 235), (190, 235)], (200, 140, 90))
poly([(220, 30), (470, 30), (470, 62), (220, 62)], (230, 225, 210))   # 간판 판(글씨는 요청문이)
# 통로로 튀어나온 카운터: 윗면·앞면, 아래 그림자
poly([(240, 240), (450, 240), (458, 256), (232, 256)], (180, 170, 160))
poly([(232, 256), (458, 256), (458, 292), (232, 292)], (120, 115, 110))
poly([(232, 292), (458, 292), (466, 300), (224, 300)], (50, 50, 50))
# 오른쪽 끝 기둥(옆면 보임)
poly([(586, 22), (W, 22), (W, H), (586, H)], (125, 120, 112))
poly([(570, 22), (586, 22), (586, H), (570, 410)], (90, 88, 82))
def person(x, y, h):
    w = h * 0.26; c = (128, 128, 128)
    d.ellipse([x - w * .35, y - h, x + w * .35, y - h + h * .14], fill=c); d.rectangle([x - w / 2, y - h + h * .14, x + w / 2, y], fill=c)
person(520, 266, 142); person(420, 410, 167)
im.save(P + '/jr_b1_p1_v2_sketch.png'); im.resize((W * 2, H * 2), Image.NEAREST).save(P + '/jr_b1_p1_v2_sketch_x2.png')
