"""손길 의원 수술실 배치 밑그림 (632×424, 참고 그림용). 사용: python3 sketch_op_v2.py <출력폴더>"""
import sys
from PIL import Image, ImageDraw
P = sys.argv[1]
W, H = 632, 424; VX, VY = 316, 52          # 소실점
im = Image.new('RGB', (W, H), (200, 200, 200)); d = ImageDraw.Draw(im); O = (40, 40, 40)
def poly(pts, fill): d.polygon([tuple(map(round, p)) for p in pts], fill=fill, outline=O)
def rect(x0, y0, x1, y1, fill): d.rectangle([x0, y0, x1, y1], fill=fill, outline=O)
def back(x, y, yb):   # 바닥 점 (x, y)를 더 안쪽 바닥 yb로 (소실점으로)
    s = (yb - VY) / (y - VY); return VX + (x - VX) * s, s
def box(x0, x1, yf, h, dep, front, top, side):
    yb = yf - dep; bx0, s = back(x0, yf, yb); bx1, _ = back(x1, yf, yb); hb = h * s
    poly([(x0, yf - h), (x1, yf - h), (bx1, yb - hb), (bx0, yb - hb)], top)
    if x1 < VX: poly([(x1, yf - h), (bx1, yb - hb), (bx1, yb), (x1, yf)], side)
    elif x0 > VX: poly([(x0, yf - h), (bx0, yb - hb), (bx0, yb), (x0, yf)], side)
    rect(x0, yf - h, x1, yf, front)
# 크기 기준 사람 (그리지 말 것)
def person(x, y, h):
    w = h * 0.26; c = (128, 128, 128); d.ellipse([x - w * 0.35, y - h, x + w * 0.35, y - h + h * 0.14], fill=c); d.rectangle([x - w / 2, y - h + h * 0.14, x + w / 2, y], fill=c)
# 방: 뒷벽 95~537, 양쪽 벽 닫음, 흰 타일 벽
rect(0, 0, W, 14, (150, 150, 150))
poly([(95, 14), (537, 14), (537, 255), (95, 255)], (242, 244, 244))
for y in range(30, 255, 20): d.line([(95, y), (537, y)], fill=(215, 220, 222))
for x in range(105, 537, 20): d.line([(x, 14), (x, 255)], fill=(215, 220, 222))
poly([(0, 342), (95, 255), (537, 255), (632, 342), (632, H), (0, H)], (150, 170, 185))
poly([(0, -2), (95, 14), (95, 255), (0, 342)], (228, 232, 232)); poly([(632, -2), (537, 14), (537, 255), (632, 342)], (228, 232, 232))
rect(150, 4, 280, 10, (250, 250, 250)); rect(352, 4, 482, 10, (250, 250, 250))
# 뒷벽: 이중 잠금 약품장(왼쪽), 세면대, 사람 들어가는 냉장고(오른쪽), 폐기물 통
rect(115, 95, 195, 255, (150, 155, 160)); rect(121, 102, 153, 200, (180, 205, 215)); rect(157, 102, 189, 200, (180, 205, 215))
for y in (130, 160): d.line([(121, y), (189, y)], fill=O)
for i, x in enumerate(range(124, 188, 6)):
    for y in (118, 146, 176): d.rectangle([x, y, x + 3, y + 10], fill=[(130, 70, 30), (210, 210, 220)][(i + y) % 2])
d.line([(150, 150), (160, 165)], fill=(90, 90, 90), width=3); rect(148, 160, 156, 170, (200, 170, 60)); rect(150, 205, 158, 215, (200, 170, 60))
rect(225, 185, 290, 200, (200, 205, 210)); rect(232, 200, 283, 255, (220, 222, 225)); rect(255, 160, 260, 185, (170, 170, 170))
box(420, 500, 262, 170, 24, (250, 250, 252), (235, 235, 238), (215, 215, 220))
rect(486, 120, 493, 210, (110, 110, 115)); d.line([(420, 130), (500, 130)], fill=(150, 150, 155), width=2)
for y in range(238, 256, 4): d.line([(430, y), (490, y)], fill=(170, 170, 175))
box(510, 530, 258, 28, 6, (200, 40, 40), (220, 70, 70), (170, 30, 30))
# 무영등: 천장에서 팔로 내려와 수술대 위
d.line([(316, 14), (316, 95)], fill=(150, 150, 155), width=4); d.line([(316, 95), (300, 110)], fill=(150, 150, 155), width=4)
d.ellipse([262, 105, 338, 135], fill=(235, 238, 240), outline=O); d.ellipse([280, 112, 320, 128], fill=(255, 255, 230), outline=O)
person(395, 262, 142)
# 링거대 (수술대 머리 쪽)
d.line([(210, 230), (210, 335)], fill=(150, 150, 155), width=3); rect(203, 230, 217, 250, (200, 230, 240)); d.line([(200, 335), (220, 335)], fill=(120, 120, 125), width=3)
# 수술대 (가운데, 긴 면이 화면, 176×79)
rect(296, 290, 336, 343, (150, 155, 160)); box(262, 370, 348, 6, 14, (120, 125, 130), (140, 145, 150), (110, 115, 120))
box(228, 404, 292, 12, 22, (170, 175, 180), (40, 40, 45), (130, 135, 140))
rect(250, 262, 300, 270, (245, 245, 245)); d.line([(240, 284), (240, 296)], fill=(110, 70, 40), width=3); d.line([(392, 284), (392, 296)], fill=(110, 70, 40), width=3)
# 기구 수레 둘
box(140, 185, 275, 5, 14, (190, 195, 200), (225, 228, 232), (160, 165, 170))
for x in (143, 182): d.line([(x, 275), (x, 335)], fill=(140, 140, 145), width=3)
box(140, 185, 318, 4, 14, (190, 195, 200), (210, 212, 215), (160, 165, 170))
for x in (150, 160, 170): d.line([(x, 262), (x + 6, 268)], fill=(90, 90, 95), width=2)
box(440, 485, 275, 5, 14, (190, 195, 200), (225, 228, 232), (160, 165, 170))
for x in (443, 482): d.line([(x, 275), (x, 335)], fill=(140, 140, 145), width=3)
box(440, 485, 318, 4, 14, (190, 195, 200), (210, 212, 215), (160, 165, 170))
for x in (450, 460, 470): d.line([(x, 262), (x + 6, 268)], fill=(90, 90, 95), width=2)
person(560, 415, 167)
im.save(P + '/op_sketch.png'); im.resize((W * 2, H * 2), Image.NEAREST).save(P + '/op_sketch_x2.png')
