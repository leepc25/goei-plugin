"""손길 의원 진료실 배치 밑그림 (632×424, 참고 그림용). 사용: python3 sketch_jinryo_v2.py <출력폴더>"""
import sys
from PIL import Image, ImageDraw
P = sys.argv[1]
W, H = 632, 424; VX, VY = 316, 52          # 소실점
im = Image.new('RGB', (W, H), (200, 200, 200)); d = ImageDraw.Draw(im); O = (40, 40, 40)
def poly(pts, fill): d.polygon([tuple(map(round, p)) for p in pts], fill=fill, outline=O)
def rect(x0, y0, x1, y1, fill): d.rectangle([x0, y0, x1, y1], fill=fill, outline=O)
def back(x, y, yb):   # 바닥 점 (x, y)를 더 안쪽 바닥 yb로 (소실점으로)
    s = (yb - VY) / (y - VY); return VX + (x - VX) * s, s
def box(x0, x1, yf, h, dep, front, top, side):
    yb = yf - dep; bx0, s = back(x0, yf, yb); bx1, _ = back(x1, yf, yb); hb = h * s
    poly([(x0, yf - h), (x1, yf - h), (bx1, yb - hb), (bx0, yb - hb)], top)
    if x1 < VX: poly([(x1, yf - h), (bx1, yb - hb), (bx1, yb), (x1, yf)], side)
    elif x0 > VX: poly([(x0, yf - h), (bx0, yb - hb), (bx0, yb), (x0, yf)], side)
    rect(x0, yf - h, x1, yf, front)
# 크기 기준 사람 (그리지 말 것)
def person(x, y, h):
    w = h * 0.26; c = (128, 128, 128); d.ellipse([x - w * 0.35, y - h, x + w * 0.35, y - h + h * 0.14], fill=c); d.rectangle([x - w / 2, y - h + h * 0.14, x + w / 2, y], fill=c)
# 방: 뒷벽 95~537, 양쪽 벽 닫음
rect(0, 0, W, 14, (150, 150, 150))
poly([(95, 14), (537, 14), (537, 255), (95, 255)], (236, 228, 200)); poly([(95, 195), (537, 195), (537, 255), (95, 255)], (170, 200, 180))
poly([(0, 342), (95, 255), (537, 255), (632, 342), (632, H), (0, H)], (160, 195, 175))
poly([(0, -2), (95, 14), (95, 255), (0, 342)], (220, 212, 185)); poly([(0, 280), (95, 195), (95, 255), (0, 342)], (160, 190, 170))
poly([(632, -2), (537, 14), (537, 255), (632, 342)], (220, 212, 185)); poly([(632, 280), (537, 195), (537, 255), (632, 342)], (160, 190, 170))
rect(160, 4, 290, 10, (250, 250, 250)); rect(342, 4, 472, 10, (250, 250, 250))
# 뒷벽: 엑스레이 판(왼쪽 위), 약장(가운데), 세면대(가운데 오른쪽), 포스터
rect(130, 90, 200, 150, (210, 225, 235)); rect(140, 98, 190, 142, (60, 70, 80))
rect(285, 120, 355, 255, (245, 245, 245)); rect(290, 125, 319, 200, (180, 205, 215)); rect(321, 125, 350, 200, (180, 205, 215))
for y in (148, 172): d.line([(290, y), (350, y)], fill=O)
for i, x in enumerate(range(293, 348, 7)):
    for y in (138, 162, 186): d.rectangle([x, y, x + 4, y + 9], fill=[(150, 90, 40), (200, 200, 210), (90, 60, 30), (220, 220, 225)][(i + y) % 4])
rect(290, 205, 350, 250, (225, 225, 225)); d.line([(320, 205), (320, 250)], fill=O)
rect(375, 185, 430, 200, (200, 205, 210)); rect(380, 200, 425, 255, (230, 230, 230)); rect(400, 160, 405, 185, (170, 170, 170))
rect(450, 90, 495, 145, (235, 230, 220))
poly([(20, 120), (55, 100), (55, 155), (20, 175)], (235, 230, 220))
person(165, 278, 145)
# 의사 책상 (왼쪽, 정면, 106×75), 뒤에 의사 설 자리
box(110, 216, 310, 75, 22, (150, 150, 155), (185, 185, 190), (125, 125, 130))
d.ellipse([130, 228, 145, 238], fill=(60, 60, 60), outline=O); rect(170, 226, 195, 236, (240, 240, 230))
# 기구 수레 (책상 오른쪽)
box(232, 262, 318, 70, 14, (190, 195, 200), (215, 220, 225), (160, 165, 170))
# 페달 휴지통
box(270, 288, 300, 26, 8, (210, 210, 215), (230, 230, 235), (180, 180, 185))
# 진찰 침대 (오른쪽, 긴 면이 화면, 167×62) + 발판 + 칸막이 병풍
box(395, 562, 360, 62, 40, (110, 140, 150), (235, 235, 235), (90, 115, 125))
box(450, 482, 384, 14, 10, (150, 150, 150), (180, 180, 180), (120, 120, 120))
for i, x in enumerate((330, 352, 374)): rect(x, 230, x + 20, 312, (170, 205, 185))
person(600, 415, 167)
im.save(P + '/jinryo_sketch.png'); im.resize((W * 2, H * 2), Image.NEAREST).save(P + '/jinryo_sketch_x2.png')
