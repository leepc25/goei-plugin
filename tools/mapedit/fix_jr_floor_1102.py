def steps(segs, x_end):
    """구간 목록 → 꺾은선. 구간이 바뀌는 곳은 4px 기울여 잇는다."""
    pts = []
    for i, (x, y) in enumerate(segs):
        nx = segs[i + 1][0] if i + 1 < len(segs) else x_end
        if pts and pts[-1][1] != y: pts.append([x + 4, y])
        elif not pts: pts.append([x, y])
        pts.append([nx, y])
    return pts


def poly(top, H):
    return [[top[0][0], H]] + top + [[top[-1][0], H]]


def put(sid, top, bottom, lane1, sizes, doors=None):
    p = ROOT / f'game-src/mapedit/{sid}/map.json'
    m = json.loads(p.read_text())
    m['floor'] = poly(top, bottom)
    m['lane'] = [min(y for _, y in top), lane1]
    m['sizes'] = sizes
    if doors: m['doors'].update(doors)
    p.write_text(json.dumps(m, ensure_ascii=False, indent=1))
    print(sid, 'lane', m['lane'], 'points', len(top))


