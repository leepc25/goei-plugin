def build(spec):
    pts=set()
    for y,(l,r) in spec['slab'].items():
        pts.update((x,y) for x in range(l,r+1))
    for x0,x1,y0,y1 in spec['legs']+spec['items']:
        pts.update((x,y) for x in range(x0,x1+1) for y in range(y0,y1+1))
    for k in ('spans','spans2'):
        for y,lst in spec.get(k,{}).items():
            for l,r in lst: pts.update((x,y) for x in range(l,r+1))
    return pts

