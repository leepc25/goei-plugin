// 사이트당 탭 하나 · 새로고침 뒤 탭 되살리기 (2026-11-08, 작업용)
import assert from 'node:assert/strict';
import { boot, closeEditor, launch, loadFixture, openWin } from './qc-settings-harness.mjs';
const fx = loadFixture(new URL('../.scratch/fixture/fixture.json', import.meta.url).pathname);
const OUT = process.argv[2] || '.scratch/br-tabs';
const browser = await launch();
const base = { message: [{ role: 'user', data: '출동', chatId: 'u1' }, { role: 'char', data: '첫 답.\n[▣|2025.01.01|02:47 AM|☀️|4°C|관리국|QC 괴이]', chatId: 'c1' }], scriptstate: { $st_faction: 'A00', $st_lang: 'ko', $st_fm: '2', $st_fixed_theme: 'dark', $st_anomaly_on: '1', $pp_on: '0' } };
const start = async (chat) => {
  const r = await boot(browser, fx, chat, 'pc');
  await openWin(r.page); await r.page.waitForTimeout(300);
  if (await r.page.evaluate(() => document.querySelector('.gw')?.hidden === false)) await closeEditor(r.page, true);
  return r;
};
let { page, errors } = await start(base);
const click = async (sel) => { const ok = await page.evaluate((s) => { const el = [...document.querySelectorAll(s)].find((e) => e.getBoundingClientRect().width > 0); el?.click(); return !!el; }, sel); assert.ok(ok, sel); await page.waitForTimeout(250); };
const tabs = () => page.evaluate(() => [...document.querySelectorAll('.br-tab')].map((t) => (t.classList.contains('on') ? '*' : '') + t.querySelector('.br-tt').textContent));
await click('[data-action="nav-tab"][data-value="net"]');
await click('.br-bm[data-value="gn"]');
await click('[data-action="br-new"]'); await click('[data-action="br-new"]');
assert.equal((await tabs()).length, 2, '빈 새 탭은 하나');
await click('.br-bm[data-value="wk"]');
await click('.br-bm[data-value="gn"]');
let t = await tabs();
assert.equal(t.length, 2, '이미 열린 괴담넷은 그 탭으로');
assert.ok(t[0].startsWith('*괴담넷'), t.join('|'));
await click('[data-action="br-new"]'); await click('.br-bm[data-value="wk"]');
t = await tabs();
assert.equal(t.length, 2, '빈 탭에서 열린 사이트를 누르면 빈 탭은 닫힌다');
assert.ok(t[1].startsWith('*괴이위키'), t.join('|'));
await click('[data-action="br-new"]'); await click('.br-bm[data-value="gal"]');
await page.screenshot({ path: `${OUT}-before.png` });
await page.waitForTimeout(2000);
const saved = await page.evaluate(() => window.__chat.scriptstate.$br_tabs);
assert.ok(saved, '탭이 채팅에 적힌다');
assert.deepEqual(errors, []);
await page.close();
({ page, errors } = await start({ ...base, scriptstate: { ...base.scriptstate, $br_tabs: saved } }));
await click('[data-action="nav-tab"][data-value="net"]');
t = await tabs();
await page.screenshot({ path: `${OUT}-after.png` });
assert.equal(t.length, 3, t.join('|'));
assert.ok(t[2].startsWith('*'), '보던 탭(괴담갤)으로');
assert.ok(await page.evaluate(() => !!document.querySelector('.br-p-gal')), '괴담갤 화면');
assert.deepEqual(errors, []);
console.log('ok', t);
await browser.close();
