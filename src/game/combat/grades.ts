/** 인물 이름(또는 몹 등급)과 역할 → NPC 상태 체력·피해 배수 */
export function npcStats(grade: NpcGrade, role?: string): { hp: number; dmgMul: number } {
  const g = GRADE[grade];
  return { hp: Math.round(BASE_HP * g.hp * (ROLE_HP[role ?? ''] ?? 1)), dmgMul: g.dmg };
}
