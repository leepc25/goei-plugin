/** 층 안내 */
export function floorLabel(depth: number): string {
  return depth <= 3 ? `${Math.max(1, depth)}층` : `B-${depth - 3}`;
}
export function announce(depth: number, rng: () => number = Math.random): string {
  const label = floorLabel(depth);
  const base = depth <= 3 ? [`띵. ${label}입니다. 문이 열립니다.`] : [`띵. ${label}입니다. 문이 열립니다.`, `띵. ${label}. 내리실 분은… 내리세요.`, `${label}입니다. 잘 다녀와요.`];
  return base[Math.floor(rng() * base.length) % base.length];
}

