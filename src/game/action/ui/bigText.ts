const H = 9;

export interface BigPal { light: string; mid: string; dark: string; /** 위→아래 계단 색 (그라데이션 아님, 도트 단) */ band?: string[] }
export const BIG_GOLD: BigPal = { light: '#fff6c8', mid: '#ffcf4a', dark: '#c27a12' };
