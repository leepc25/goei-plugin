RETRY = 0.25   # 쟈알디 실측 결함률

def summary(key):
    P = ALL[key]
    gen = [p for p in P if p[2] > 1]
    frames = sum(p[2] for p in gen)
    clip_cost = sum(cost(p[2]) for p in gen)
    extra = sum(c for _, c in EXTRA[key])
    retry = round(len(gen) * RETRY) * 3
    return dict(clips=len(P), gen=len(gen), frames=frames, clip_cost=clip_cost, extra=extra,
                first=clip_cost + extra, retry=retry, cap=clip_cost + extra + retry)

