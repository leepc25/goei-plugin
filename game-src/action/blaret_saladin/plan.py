# 소환체: (이름, 기준 그림 후보 회수, [(클립, 장, 생성 방식)])
SUMMONS = [
    ("성기사(블라렛)", 4, [("idle", 4, "skel"), ("march", 8, "skel"), ("slash", 6, "skel")]),
    ("성전 병사(살라딘, 칼·방패)", 4, [("march", 8, "skel"), ("slash", 6, "skel"), ("rise", 8, "skel")]),
    ("고위 맘루크(자폭)", 4, [("run", 8, "skel")]),
    ("현대 영령(로켓)", 4, [("fire", 6, "skel")]),
    ("맘루크 중기병(말+기수)", 4, [("gallop", 8, "text")]),
]


def cost(frames: int, how: str = "skel") -> int:
    if how == "text":
        return 8
    if frames <= 3:
        return 2
    if frames <= 14:
        return 3
    return 4


if __name__ == "__main__":
    tot = {}
    for name, rows in (("블라렛", BLARET), ("살라딘", SALADIN)):
        c = sum(cost(f) for _, f, _, _ in rows)
        fight = sum(1 for r in rows if r[2] == "전투")
        frames = sum(r[1] for r in rows)
        print(f"{name}: {len(rows)}클립 (전투 {fight}, 상호 {len(rows) - fight}), {frames}장, 생성 {c}회")
        tot[name] = c
    s = 0
    for name, base, clips in SUMMONS:
        c = base + sum(cost(f, h) for _, f, h in clips)
        s += c
        print(f"  소환 {name}: {len(clips)}클립, 기준 {base} + 동작 {c - base} = {c}")
    tot["소환체"] = s
    tot["기준 그림 2명 × 4"] = 8
    tot["옷 보정(edit_image_pixen)"] = 10
    tot["컷인 얼굴 2명 × 2"] = 4
    first = sum(tot.values())
    reserve_clips = round((len(BLARET) + len(SALADIN)) * 0.25)
    reserve = reserve_clips * 3 + 12
    for k, v in tot.items():
        print(f"{k}: {v}")
    print(f"1차 합계 {first}, 예비 {reserve}(사람 {reserve_clips}클립×3 + 소환 12), 상한 {first + reserve}")
