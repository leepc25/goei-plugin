"""망상홈쇼핑 방송 장면 구도 선 밑그림 400×300(4:3), 투명 바탕·선만(사용자 11-09 「색 칠하지 말고 투명 배경에 선으로만」). v3 자리를 400/448로 줄임."""
from PIL import Image, ImageDraw
W,H=400,300; s=400/448
im=Image.new('RGBA',(W,H),(0,0,0,0)); d=ImageDraw.Draw(im); C=(0,0,0,255)
P=lambda *xy:[round(v*s) for v in xy]
L=lambda *xy:d.line(P(*xy),fill=C,width=1)
R=lambda *xy:d.rectangle(P(*xy),outline=C,width=1)
L(0,34,448,34); L(0,10,448,10); L(0,28,448,28)                 # 트러스
for x in range(24,448,52): R(x,12,x+14,30)                      # 조명
L(0,250,448,250)                                                 # 뒷벽과 바닥 경계
for x in range(56,448,56): L(x,36,x,250)                         # 세트 판 이음
R(262,46,436,86)                                                 # 전광판
R(400,96,446,232); [L(400,y,446,y) for y in (130,165,200)]       # 소품 선반
d.rectangle(P(262,100,392,228),fill=(0,0,0,0)); R(262,100,392,228)   # 상품 뒤 벽 칸(안 비움)
# 앞 물건이 뒤 선을 가림: 먼저 투명으로 지우고 윤곽만
d.polygon(P(40,250,54,150,100,136,152,136,198,150,212,250),fill=(0,0,0,0))
d.rectangle(P(30,232,226,336),fill=(0,0,0,0)); d.rectangle(P(258,222,440,336),fill=(0,0,0,0))
d.ellipse(P(92,52,160,128),fill=(0,0,0,0)); d.rectangle(P(114,126,138,138),fill=(0,0,0,0))
d.ellipse(P(92,52,160,128),outline=C)                            # 얼굴
d.arc(P(88,40,164,100),180,360,fill=C)                           # 머리칼
d.ellipse(P(106,78,122,92),outline=C); d.ellipse(P(130,78,146,92),outline=C)
d.arc(P(108,96,144,116),10,170,fill=C)                           # 입
L(114,126,114,138); L(138,126,138,138)                           # 목
d.line(P(40,250,54,150,100,136,152,136,198,150,212,250),fill=C)  # 어깨·몸
d.line(P(112,138,126,190,140,138),fill=C)                        # 깃
d.line(P(122,142,120,196,132,196,130,142),fill=C)               # 넥타이
R(30,232,226,336)                                                # 단상
d.ellipse(P(60,222,96,240),outline=C); d.ellipse(P(160,222,196,240),outline=C)   # 손
d.line(P(268,222,430,222,440,232,258,232,268,222),fill=C); R(258,232,440,336)    # 시연 테이블
L(0,326,448,326)                                                 # 바닥 테이프
im.save('sketch_ds_studio_v4.png')
