"""망상홈쇼핑 방송 장면 구도 밑그림 448×336(브라운관 4:3). pixflux init_image용(11-09).
진행자 왼쪽 크게(머리~가슴, 단상이 아래 가림), 시연 테이블 오른쪽(윗면 y≈232, 상품 85도트 x 300~385), 맨 위 조명 트러스, 뒷벽 세트."""
from PIL import Image, ImageDraw
W,H=448,336
im=Image.new('RGB',(W,H),(20,10,14)); d=ImageDraw.Draw(im)
# 뒷벽: 빨강·검정 판, 금테
for i,x in enumerate(range(0,W,56)):
    d.rectangle([x,36,x+55,250],fill=(120,18,26) if i%2==0 else (30,14,18)); d.line([x,36,x,250],fill=(190,150,60))
d.rectangle([0,250,W,H],fill=(14,10,12))                         # 무대 바닥(검은 광택)
for x in range(0,W,40): d.line([x,252,x+20,H],fill=(40,30,36))
# 위 조명 트러스와 조명
d.rectangle([0,0,W,34],fill=(8,6,8)); d.line([0,10,W,10],fill=(70,70,78),width=3); d.line([0,28,W,28],fill=(70,70,78),width=3)
for x in range(24,W,52): d.rectangle([x,12,x+14,30],fill=(50,50,56)); d.polygon([(x+2,30),(x+12,30),(x+40,250),(x-26,250)],outline=(70,50,50))
# 오른쪽 위 매출 전광판(빨간 숫자 자리)
d.rectangle([262,46,436,86],fill=(16,8,8),outline=(150,150,160)); [d.rectangle([272+i*24,54,288+i*24,78],fill=(200,30,30)) for i in range(7)]
# 오른쪽 벽 아래: 소품 선반(상품 뒤는 어둡게 비움)
d.rectangle([400,96,446,232],fill=(40,26,24)); [d.line([400,y,446,y],fill=(90,70,50)) for y in (130,165,200)]
d.rectangle([262,100,392,228],fill=(26,12,16))                   # 상품 뒤 어두운 벽(상품이 뜨게)
# 진행자: 머리~가슴(검은 정장·흰 얼굴), 가로 40~210
d.ellipse([92,52,160,128],fill=(232,228,222))                    # 얼굴
d.pieslice([88,40,164,100],180,360,fill=(16,14,16))              # 머리칼
d.ellipse([106,78,122,92],fill=(5,5,5)); d.ellipse([130,78,146,92],fill=(5,5,5))   # 큰 검은 눈
d.arc([108,96,144,116],10,170,fill=(150,40,40),width=2)          # 입 다문 미소
d.rectangle([114,126,138,140],fill=(232,228,222))                # 목
d.polygon([(40,250),(54,150),(100,136),(152,136),(198,150),(212,250)],fill=(18,18,22))   # 정장 어깨~가슴
d.polygon([(112,138),(140,138),(126,190)],fill=(240,240,240)); d.polygon([(122,142),(130,142),(132,196),(120,196)],fill=(60,10,14))  # 셔츠·넥타이
# 단상(빨강 광택, 크롬 테) 진행자 아래를 가림
d.rectangle([30,232,226,336],fill=(150,20,28)); d.line([30,232,226,232],fill=(220,220,230),width=3)
d.ellipse([60,222,96,240],fill=(232,228,222)); d.ellipse([160,222,196,240],fill=(232,228,222))   # 단상 위 두 손
# 시연 테이블: 흰 천, 윗면 비움
d.rectangle([258,232,440,336],fill=(228,226,230)); d.polygon([(258,232),(440,232),(430,222),(268,222)],fill=(245,245,250))
for x in range(268,440,22): d.line([x,240,x+4,336],fill=(200,198,206))
# 왼쪽 아래 노랑·검정 바닥 테이프 앞쪽
for x in range(0,W,16): d.rectangle([x,326,x+7,333],fill=(220,190,30))
im.save('sketch_ds_studio_v3.png')
